#!/usr/bin/env python3
"""
pass 111 — build the native content pack.

The gradle asset pipeline in cloud release builds mangles every metro-bundled
asset (they land flattened under res/ with obfuscated names instead of the
assets/raw + assets/drawable-* layout the JS resolver expects), so release
APKs cannot read ANY require()'d file: images, fonts, quran/hadith txt/gz.

Instead of fighting gradle, the app now downloads ONE zip on first native
launch and unpacks it into documentDirectory/native-pack/. Everything else
(custom asset transformer, fonts.ts, content.ts) reads from there. The web
build is untouched — it keeps using metro's export assets.

Pack layout mirrors project-relative paths so the transformer can map
httpServerLocation ('./assets/content/quran') straight onto the pack:

  assets/content/**   (quran/hadith txt + gz, duas, names, seerah, quiz)
  assets/img/**       (mecca.jpg, patterns, logo-export…)
  assets/images/**    (icons, illustrations)
  assets/avatars/**   (default avatars)
  assets/shop/**      (shop banners)
  src/fonts/**        (Poppins/Amiri/ArefRuqaa/Sora/Manrope)

Excluded: assets/content.zip (dup), assets/vid (unused, 11MB), expo.icon.

Outputs:
  out/pack.zip                     — hosted at <api>/native-pack/pack.zip
  out/pack.json                    — {version, bytes, sha256, files}
  src/lib/packMeta.ts              — generated constants imported by the app

Usage:  python3 scripts/build-native-pack.py [--out /tmp/native-pack]
"""
import hashlib
import json
import os
import sys
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INCLUDE_DIRS = [
    "assets/content",
    "assets/img",
    "assets/images",
    "assets/avatars",
    "assets/shop",
    "src/fonts",
    # pass 114 - @expo/vector-icons ships its glyph fonts as .ttf modules
    # from node_modules; without them every FontAwesome5/Ionicons glyph
    # renders blank in release APKs (same gradle asset problem).
    "node_modules/@expo/vector-icons/build/vendor/react-native-vector-icons/Fonts",
]
PACK_URL = "https://app.deenlink.org/native-pack/pack.zip"


def main() -> int:
    out = "/tmp/native-pack"
    if "--out" in sys.argv:
        out = sys.argv[sys.argv.index("--out") + 1]
    os.makedirs(out, exist_ok=True)
    zpath = os.path.join(out, "pack.zip")

    files = []
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED, compresslevel=6) as z:
        for d in INCLUDE_DIRS:
            base = os.path.join(ROOT, d)
            if not os.path.isdir(base):
                print(f"  WARN: missing {d}", file=sys.stderr)
                continue
            for dirpath, _dirnames, filenames in os.walk(base):
                for fn in sorted(filenames):
                    full = os.path.join(dirpath, fn)
                    rel = os.path.relpath(full, ROOT).replace(os.sep, "/")
                    # ZIP_DEFLATED on already-gz content is wasted CPU but harmless
                    z.write(full, rel)
                    files.append(rel)

    data = open(zpath, "rb").read()
    sha = hashlib.sha256(data).hexdigest()
    version = sha[:16]
    meta = {
        "version": version,
        "sha256": sha,
        "bytes": len(data),
        "files": len(files),
        "url": PACK_URL,
    }
    with open(os.path.join(out, "pack.json"), "w") as f:
        json.dump(meta, f, indent=1)

    ts = os.path.join(ROOT, "src/lib/packMeta.ts")
    with open(ts, "w") as f:
        f.write(
            "/* GENERATED by scripts/build-native-pack.py — do not edit.\n"
            " * pass 111 — identity of the native content pack hosted on the API\n"
            " * domain. Bumping PACK_VERSION makes installed apps re-download. */\n"
            f"export const PACK_URL = '{PACK_URL}';\n"
            f"export const PACK_VERSION = '{version}';\n"
            f"export const PACK_BYTES = {len(data)};\n"
            f"export const PACK_SHA256 = '{sha}';\n"
        )

    print(f"  pack.zip: {len(data)/1048576:.1f} MB, {len(files)} files")
    print(f"  version : {version}")
    print(f"  wrote   : {zpath}")
    print(f"            {os.path.join(out, 'pack.json')}")
    print(f"            {ts}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
